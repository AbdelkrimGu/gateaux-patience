// One-off: outline "Gateaux Patience" in Dela Gothic One and write the paths
// to src/components/ui/wordmark-paths.ts, so the wordmark is identical in every
// locale and Arabic pages never download Dela (DESIGN.md amendment 5).
//
//   node scripts/build-wordmark.mjs
//
// The TTF (OFL, google/fonts) is downloaded to assets-src/fonts/ (gitignored)
// on first run. Re-run only if the wordmark text or font changes.

import { existsSync, mkdirSync, writeFileSync, readFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import opentype from "opentype.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TTF = join(ROOT, "assets-src", "fonts", "DelaGothicOne-Regular.ttf");
const URL_TTF = "https://github.com/google/fonts/raw/main/ofl/delagothicone/DelaGothicOne-Regular.ttf";
const OUT = join(ROOT, "src", "components", "ui", "wordmark-paths.ts");

if (!existsSync(TTF)) {
  mkdirSync(dirname(TTF), { recursive: true });
  const res = await fetch(URL_TTF);
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  writeFileSync(TTF, Buffer.from(await res.arrayBuffer()));
}

const buf = readFileSync(TTF);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const SIZE = 100; // font units -> 100px em
const TRACK = -0.01 * SIZE; // B §7: brand set at -0.01em

// Own serializer: opentype.js 2.0's toPathData(decimals) emits NaN for some
// quadratic control points.
const r = (n) => {
  const v = Math.round(n * 10) / 10;
  return Object.is(v, -0) ? "0" : String(v);
};
function serialize(path) {
  return path.commands
    .map((c) => {
      if (c.type === "M" || c.type === "L") return `${c.type}${r(c.x)} ${r(c.y)}`;
      if (c.type === "Q") return `Q${r(c.x1)} ${r(c.y1)} ${r(c.x)} ${r(c.y)}`;
      if (c.type === "C") return `C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${r(c.x)} ${r(c.y)}`;
      return "Z";
    })
    .join("");
}

function outline(text) {
  // Lay glyphs out by hand to apply tracking + kerning.
  const glyphs = font.stringToGlyphs(text);
  const scale = SIZE / font.unitsPerEm;
  let x = 0;
  const parts = [];
  const all = new opentype.Path();
  glyphs.forEach((g, i) => {
    const p = g.getPath(x, 0, SIZE);
    parts.push(serialize(p));
    all.extend(p);
    x += g.advanceWidth * scale + TRACK;
    if (i < glyphs.length - 1) x += font.getKerningValue(g, glyphs[i + 1]) * scale;
  });
  const bb = all.getBoundingBox();
  return {
    d: parts.join(""),
    width: Math.ceil(x - TRACK),
    top: Math.floor(bb.y1),
    bottom: Math.ceil(bb.y2),
  };
}

const l1 = outline("Gateaux");
const l2 = outline("Patience");
// Inline layout = line 2 shifted right by the advance of "Gateaux ".
const inlineDx = Math.round((outline("Gateaux ").width + TRACK) * 10) / 10;
const ascent = Math.min(l1.top, l2.top);
const descent = Math.max(l1.bottom, l2.bottom);
const lineH = descent - ascent;
const GAP = 6;
const stackedW = Math.max(l1.width, l2.width);
const inlineW = Math.ceil(inlineDx + l2.width);

// Both layouts reuse the same two path strings, so a page that renders both
// (mobile + desktop header) pays for them once after gzip.
const src = `// GENERATED by scripts/build-wordmark.mjs from Dela Gothic One (OFL). Do not edit.
// Baseline at y=0 (100px em). Glyphs span y=${ascent}..${descent}.

export const WORDMARK = {
  line1: ${JSON.stringify(l1.d)},
  line2: ${JSON.stringify(l2.d)},
  inline: { viewBox: "0 ${ascent} ${inlineW} ${lineH}", line2Dx: ${inlineDx}, line2Dy: 0 },
  stacked: { viewBox: "0 ${ascent} ${stackedW} ${lineH * 2 + GAP}", line2Dx: 0, line2Dy: ${lineH + GAP} },
} as const;
`;
writeFileSync(OUT, src);
console.log(`wrote ${OUT}: inline ${inlineW}x${lineH}, stacked ${stackedW}x${lineH * 2 + GAP}`);
